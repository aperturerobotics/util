//go:build generate

package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"
)

type GoDistEntry struct {
	GOOS   string `json:"GOOS"`
	GOARCH string `json:"GOARCH"`
}

func main() {
	output, err := exec.Command("go", "tool", "dist", "list", "-json").Output()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error running 'go tool dist list -json': %v\n", err)
		os.Exit(1)
	}

	var entries []GoDistEntry
	if err := json.Unmarshal(output, &entries); err != nil {
		fmt.Fprintf(os.Stderr, "Error unmarshaling JSON output: %v\n", err)
		os.Exit(1)
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by generate.go. DO NOT EDIT.\n\n")
	out.WriteString("package gotargets\n\n")
	out.WriteString("// GoDistEntry is one target the Go toolchain supports.\n")
	out.WriteString("type GoDistEntry struct {\n\t// GOOS is the target operating system.\n\tGOOS string `json:\"GOOS\"`\n\t// GOARCH is the target architecture.\n\tGOARCH string `json:\"GOARCH\"`\n}\n\n")
	out.WriteString("// KnownGoDists lists the targets from go tool dist list.\n")
	out.WriteString("var KnownGoDists = []*GoDistEntry{\n")
	for _, entry := range entries {
		fmt.Fprintf(&out, "\t{\n")
		fmt.Fprintf(&out, "\t\tGOOS: %q,\n", entry.GOOS)
		fmt.Fprintf(&out, "\t\tGOARCH: %q,\n", entry.GOARCH)
		fmt.Fprintf(&out, "\t},\n")
	}
	out.WriteString("}\n")

	// Format the source as gofmt would.
	src, err := format.Source(out.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error formatting gotargets.gen.go: %v\n", err)
		os.Exit(1)
	}

	err = os.WriteFile("gotargets.gen.go", src, 0o644)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error writing gotargets.gen.go: %v\n", err)
		os.Exit(1)
	}
}
